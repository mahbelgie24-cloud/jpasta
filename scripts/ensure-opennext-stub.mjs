#!/usr/bin/env node
/**
 * Ensure a type stub exists for the OpenNext-generated worker.
 *
 * `worker.ts` imports `./.open-next/worker.js`, which only exists after
 * `opennextjs-cloudflare build`. Typechecking (next typegen/tsc) and plain
 * `next build` run before that, so we provide a declaration file. When the
 * real worker exists, TypeScript still prefers this declaration — the
 * runtime bundle is produced by wrangler/esbuild, not tsc.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";

const dir = ".open-next";
const dts = `${dir}/worker.d.ts`;
mkdirSync(dir, { recursive: true });

if (!existsSync(dts)) {
  writeFileSync(
    dts,
    `// Generated by scripts/ensure-opennext-stub.mjs — do not edit.
declare const handler: {
  fetch(request: Request, env: unknown, ctx: unknown): Promise<Response>;
};
export default handler;
export declare const DOQueueHandler: unknown;
export declare const DOShardedTagCache: unknown;
export declare const BucketCachePurge: unknown;
`,
  );
}
